import unittest

from memgen import (
    constant,
    expr,
    format_coe,
    format_mem,
    format_mif,
    generate,
    rampl,
    random_data,
    sine,
    square,
    sawtooth,
    triangle,
)
from memgen.core import MemoryError, format_value, normalize_values, parse_values


class TestNormalize(unittest.TestCase):
    def test_mask_unsigned(self):
        self.assertEqual(normalize_values([0x1FFFF], 16), [0xFFFF])

    def test_signed_wrap(self):
        self.assertEqual(normalize_values([128], 8, signed=True), [-128])
        self.assertEqual(normalize_values([-1], 8, signed=True), [-1])
        self.assertEqual(normalize_values([127], 8, signed=True), [127])

    def test_parse_values(self):
        self.assertEqual(parse_values("0x10, 16 -1"), [0x10, 16, -1])


class TestFormatValue(unittest.TestCase):
    def test_widths(self):
        self.assertEqual(format_value(0, 16, 16), "0000")
        self.assertEqual(format_value(0xFFFF, 16, 16), "FFFF")
        self.assertEqual(format_value(5, 8, 2), "00000101")
        self.assertEqual(format_value(0o7, 8, 8), "007")
        self.assertEqual(format_value(-1, 8, 10), "-1")


class TestGenerators(unittest.TestCase):
    def test_constant(self):
        self.assertEqual(constant(7, 4), [7, 7, 7, 7])

    def test_ramp(self):
        self.assertEqual(rampl(4, start=2, step=3), [2, 5, 8, 11])

    def test_sine_bounds(self):
        vals = sine(64, cycles=2)
        self.assertEqual(len(vals), 64)
        self.assertTrue(all(-128 <= v <= 127 for v in vals))

    def test_sine_deterministic(self):
        self.assertEqual(sine(32), sine(32))

    def test_saw_and_triangle(self):
        saw = sawtooth(4)
        self.assertEqual(saw, [-127, -64, 0, 64])
        self.assertEqual(sawtooth(4, reverse=True), [127, 64, 0, -64])
        tri = triangle(4)
        self.assertTrue(all(-128 <= v <= 127 for v in tri))

    def test_square_duty(self):
        sq = square(4, duty=0.5)
        self.assertEqual(sq, [127, 127, -127, -127])
        self.assertEqual(square(4, duty=0.25), [127, -127, -127, -127])

    def test_random_seed(self):
        self.assertEqual(random_data(10, seed=1), random_data(10, seed=1))
        self.assertTrue(all(0 <= v <= 255 for v in random_data(10, seed=1)))

    def test_expr(self):
        self.assertEqual(expr("x", 4), [0, 1, 2, 3])
        self.assertEqual(expr("x*x", 4), [0, 1, 4, 9])
        self.assertEqual(expr("sin(x)*100", 1), [0])

    def test_expr_bad(self):
        with self.assertRaises(ValueError):
            expr("__import__('os')", 2)


class TestFormats(unittest.TestCase):
    def test_coe(self):
        text = format_coe([0, 1, 0x10], width=16, radix=16, comment="hi")
        self.assertIn("memory_initialization_radix=16;", text)
        self.assertIn("memory_initialization_vector=", text)
        self.assertIn("  0000,\n  0001,\n  0010;", text)
        self.assertIn("; hi", text)

    def test_mem_rejects_other_radix(self):
        with self.assertRaises(MemoryError):
            format_mem([1], radix=10)

    def test_mem(self):
        text = format_mem([0, 1, 2], width=8, radix=16)
        self.assertIn("// Generated by memgen", text)
        self.assertEqual(text.splitlines()[-3:], ["00", "01", "02"])

    def test_mif(self):
        text = format_mif([0, 1, 2], width=8, radix=16)
        self.assertIn("DEPTH = 3;", text)
        self.assertIn("WIDTH = 8;", text)
        self.assertIn("ADDRESS_RADIX = HEX;", text)
        self.assertIn("DATA_RADIX = HEX;", text)
        self.assertIn("  0 : 00;", text)
        self.assertIn("  2 : 02;", text)
        self.assertTrue(text.strip().endswith("END;"))

    def test_generate_dispatch(self):
        self.assertEqual(generate("mem", [1], width=4), format_mem([1], width=4))
        with self.assertRaises(MemoryError):
            generate("nope", [1])


if __name__ == "__main__":
    unittest.main()
