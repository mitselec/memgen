"""Renderers for the supported memory initialization formats."""

from __future__ import annotations

from typing import Optional

from memgen.core import (
    RADIX_NAMES,
    Memory,
    MemoryError,
    format_value,
    normalize_values,
)

__all__ = ["format_coe", "format_mem", "format_mif", "generate"]


def _prepare(
    values, width: int, radix: int, signed: bool
) -> Memory:
    mem = Memory(normalize_values(values, width, signed), width, radix, signed)
    if radix not in (2, 8, 10, 16):
        raise MemoryError(f"radix {radix} not supported")
    return mem


def format_coe(
    values, width: int = 16, radix: int = 16, signed: bool = False, comment: Optional[str] = None
) -> str:
    """Render a Xilinx ``.coe`` file."""
    mem = _prepare(values, width, radix, signed)
    lines = []
    if comment is None:
        comment = f"Generated by memgen: depth={mem.depth}, width={width}"
    for c in comment.splitlines():
        lines.append(f"; {c}")
    lines.append("memory_initialization_radix=" + str(radix) + ";")
    lines.append("memory_initialization_vector=")
    body = (",\n").join("  " + format_value(v, width, radix) for v in mem.values)
    lines.append(body + ";")
    return "\n".join(lines) + "\n"


def format_mem(
    values, width: int = 16, radix: int = 16, signed: bool = False, comment: Optional[str] = None
) -> str:
    """Render a Verilog ``.mem`` file (``$readmemh`` if radix 16, else ``$readmemb``)."""
    if radix not in (2, 16):
        raise MemoryError(".mem files support radix 2 (readmemb) or 16 (readmemh) only")
    mem = _prepare(values, width, radix, signed)
    lines = []
    if comment is None:
        comment = f"Generated by memgen: depth={mem.depth}, width={width}"
    for c in comment.splitlines():
        lines.append(f"// {c}")
    for v in mem.values:
        lines.append(format_value(v, width, radix))
    return "\n".join(lines) + "\n"


def format_mif(
    values, width: int = 16, radix: int = 16, signed: bool = False, comment: Optional[str] = None
) -> str:
    """Render an Intel/Altera Quartus ``.mif`` file."""
    mem = _prepare(values, width, radix, signed)
    name = RADIX_NAMES[radix]
    lines = []
    if comment is None:
        comment = f"Generated by memgen: depth={mem.depth}, width={width}"
    for c in comment.splitlines():
        lines.append(f"-- {c}")
    lines.append(f"DEPTH = {mem.depth};")
    lines.append(f"WIDTH = {width};")
    lines.append(f"ADDRESS_RADIX = {name};")
    lines.append(f"DATA_RADIX = {name};")
    lines.append("")
    lines.append("CONTENT")
    lines.append("BEGIN")
    addr_digits = len(f"{mem.depth - 1:X}") if radix == 16 else len(str(mem.depth - 1))
    data_digits = len(format_value((1 << width) - 1, width, radix))
    for i, v in enumerate(mem.values):
        addr = f"{i:X}" if radix == 16 else str(i)
        data = format_value(v, width, radix)
        lines.append(f"  {addr.rjust(addr_digits)} : {data.rjust(data_digits)};")
    lines.append("END;")
    return "\n".join(lines) + "\n"


FORMATTERS = {"coe": format_coe, "mem": format_mem, "mif": format_mif}


def generate(
    fmt: str, values, width: int = 16, radix: int = 16, signed: bool = False
) -> str:
    """Render ``values`` in one of the supported formats by name."""
    try:
        formatter = FORMATTERS[fmt]
    except KeyError:
        raise MemoryError(f"unknown format {fmt!r}: expected coe, mem or mif") from None
    return formatter(values, width=width, radix=radix, signed=signed)
